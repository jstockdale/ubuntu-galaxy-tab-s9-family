#!/usr/bin/env python3
"""Generate the AMSA10FA01 60 Hz gamma tables for panel-samsung-ana38407.c.

Samsung's SM-X710 kernel ships the panel's calibration as a text file,
vendor/qcom/opensource/display-drivers/msm/samsung/panel_data_file/
GTS9_ANA38407_AMSA10FA01.dat (GPL-2.0).  In the normal-speed 60 Hz mode the
DDIC needs a per-brightness gamma LUT offset (GLUT_OFFSET_60HS, one 192-byte
row per platform brightness level); at 120 Hz the same registers are cleared.
The platform level is looked up from the DCS 0x51 value through
NORMAL_CANDELA_MAP (<level> <WRDISBV> <cd>).

Only the 256 normal levels are emitted: the driver drives HBM solely for the
fingerprint sensor and keeps the user's row there.  Identical rows are stored
once and selected through an index (168 rows instead of 256).

Usage, from the repository root:
    python3 scripts/gen-ana38407-glut.py
        <...>/panel_data_file/GTS9_ANA38407_AMSA10FA01.dat
        kernel/drivers/panel-samsung-ana38407-glut.h
"""

import argparse
import hashlib
import re
from pathlib import Path

GLUT_LEN = 110 + 82  # DCS 0xEB at gpara 0x91, then DCS 0xEC
NORMAL_LEVELS = 256


def block(lines: list[str], name: str) -> list[str]:
    for i, line in enumerate(lines):
        if re.match(rf'^{name}\s*=\s*"', line):
            body = []
            for entry in lines[i + 1:]:
                if entry.startswith('"'):
                    return body
                body.append(entry)
            break
    raise SystemExit(f"{name} not found or not terminated")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("dat", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()

    raw = args.dat.read_bytes()
    lines = raw.decode("latin-1").split("\n")

    rows = []
    for line in block(lines, "GLUT_OFFSET_60HS"):
        values = re.findall(r"0x([0-9A-Fa-f]{2})", line)
        if values:
            rows.append(bytes(int(v, 16) for v in values))
    if len(rows) < NORMAL_LEVELS:
        raise SystemExit(f"GLUT_OFFSET_60HS has {len(rows)} rows")
    if any(len(r) != GLUT_LEN for r in rows):
        raise SystemExit("GLUT_OFFSET_60HS row is not 192 bytes")
    rows = rows[:NORMAL_LEVELS]

    wrdisbv = []
    for line in block(lines, "NORMAL_CANDELA_MAP"):
        fields = line.split()
        if len(fields) >= 3 and fields[0].isdigit():
            if int(fields[0]) != len(wrdisbv):
                raise SystemExit("NORMAL_CANDELA_MAP levels are not contiguous")
            wrdisbv.append(int(fields[1]))
    if len(wrdisbv) != NORMAL_LEVELS:
        raise SystemExit(f"NORMAL_CANDELA_MAP has {len(wrdisbv)} levels")
    if any(b <= a for a, b in zip(wrdisbv, wrdisbv[1:])):
        raise SystemExit("NORMAL_CANDELA_MAP is not strictly increasing")

    distinct: list[bytes] = []
    index = []
    for row in rows:
        if row not in distinct:
            distinct.append(row)
        index.append(distinct.index(row))
    if len(distinct) > 256:
        raise SystemExit("more distinct rows than a u8 index can address")

    out = [
        "/* SPDX-License-Identifier: GPL-2.0-only */",
        "/*",
        " * Generated by scripts/gen-ana38407-glut.py from Samsung's SM-X710 panel",
        " * data file GTS9_ANA38407_AMSA10FA01.dat (GPL-2.0), sha256",
        f" * {hashlib.sha256(raw).hexdigest()}.  Do not edit.",
        " *",
        " * ana38407_amsa10fa01_wrdisbv[]: NORMAL_CANDELA_MAP, the DCS 0x51 value of",
        " * each platform brightness level 0..255.",
        " * ana38407_amsa10fa01_glut60[]: the distinct GLUT_OFFSET_60HS rows; the first",
        " * 110 bytes go to DCS 0xEB at gpara 0x91, the other 82 to DCS 0xEC.",
        " * ana38407_amsa10fa01_glut60_row[]: row used at each platform level.",
        " */",
        "#ifndef PANEL_SAMSUNG_ANA38407_GLUT_H",
        "#define PANEL_SAMSUNG_ANA38407_GLUT_H",
        "",
        "#define ANA38407_GLUT_EB_LEN\t110",
        "#define ANA38407_GLUT_EC_LEN\t82",
        "",
        f"static const u16 ana38407_amsa10fa01_wrdisbv[{NORMAL_LEVELS}] = {{",
    ]
    for off in range(0, NORMAL_LEVELS, 12):
        out.append("\t" + ", ".join(str(v) for v in wrdisbv[off:off + 12]) + ",")
    out.append("};")
    out.append("")
    out.append(f"static const u8 ana38407_amsa10fa01_glut60_row[{NORMAL_LEVELS}] = {{")
    for off in range(0, NORMAL_LEVELS, 16):
        out.append("\t" + ", ".join(str(v) for v in index[off:off + 16]) + ",")
    out.append("};")
    out.append("")
    out.append("static const u8 ana38407_amsa10fa01_glut60"
               f"[{len(distinct)}][ANA38407_GLUT_EB_LEN + ANA38407_GLUT_EC_LEN] = {{")
    for number, row in enumerate(distinct):
        first = index.index(number)
        out.append(f"\t{{\t/* {number}: from level {first} */")
        for off in range(0, GLUT_LEN, 12):
            out.append("\t\t" + ", ".join(f"0x{b:02x}" for b in row[off:off + 12]) + ",")
        out.append("\t},")
    out.append("};")
    out.append("")
    out.append("#endif /* PANEL_SAMSUNG_ANA38407_GLUT_H */")
    out.append("")
    args.output.write_text("\n".join(out))


if __name__ == "__main__":
    main()
